"""Shared SQLAlchemy declarative base and reusable mixins.

Every domain model MUST inherit from `Base` (via these mixins) and MUST NOT redefine
primary key, timestamp, or soft-delete columns individually. This is the ONLY place
SQLAlchemy's declarative Base is defined anywhere in the project.
"""
import uuid
from datetime import datetime, timezone
from typing import Optional

from sqlalchemy import Boolean, DateTime, text
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column


class Base(DeclarativeBase):
    """The single SQLAlchemy declarative base for the entire application."""
    pass


def _utcnow() -> datetime:
    """Default factory for timestamp columns — always UTC."""
    return datetime.now(timezone.utc)


class UUIDPKMixin:
    """Adds a server-generated UUID primary key column named `id`.

    Generated by Postgres itself via gen_random_uuid() (built into core since
    PostgreSQL 13, no pgcrypto extension required) — not by Python — per the
    "UUID, generated server-side" convention in PROJECT_STATE.md §7.1.
    """

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        server_default=text("gen_random_uuid()"),
    )


class TimestampMixin:
    """Adds `created_at` / `updated_at` UTC timestamp columns."""

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=_utcnow, nullable=False
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=_utcnow, onupdate=_utcnow, nullable=False
    )


class SoftDeleteMixin:
    """Adds soft-delete columns. Business records are never hard-deleted.

    `deleted_by_staff_id` intentionally has NO ForeignKey/relationship declared here —
    a shared core mixin must never import a domain model (that would violate the
    no-cross-domain-model-import rule). Domains that want a real FK to iam.staff_user
    should declare it explicitly on the concrete model within their own domain.
    """

    is_deleted: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    deleted_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)
    deleted_by_staff_id: Mapped[Optional[uuid.UUID]] = mapped_column(
        UUID(as_uuid=True), nullable=True
    )